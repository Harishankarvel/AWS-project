/**
 * Finds the most relevant emoji icon for a given produce name
 */
export function suggestProduceIcon(name = '') {
  if (!name) return '🌾';
  const clean = name.toLowerCase().trim();

  // 1. Exact or keyword match
  for (const item of PRODUCE_ICONS) {
    if (item.keywords.some(kw => clean.includes(kw) || kw.includes(clean))) {
      return item.emoji;
    }
  }

  // 2. Specific quick fallbacks
  if (clean.includes('cane') || clean.includes('sugar')) return '🎋';
  if (clean.includes('grass') || clean.includes('hay')) return '🌾';
  if (clean.includes('tea') || clean.includes('coffee')) return '🌿';
  if (clean.includes('dal') || clean.includes('pulse')) return '🫛';

  return '🌾';
}
