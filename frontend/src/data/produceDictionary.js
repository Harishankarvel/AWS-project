/**
 * Normalizes input english string: cleans punctuation, lowers case, trims extra whitespace
 */
function normalizeText(text) {
  if (!text) return '';
  return text.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').trim();
}

/**
 * Translates a single english commodity term or phrase using the dictionary
 */
export function translateProduceName(englishName) {
  if (!englishName || typeof englishName !== 'string') {
    return { en: englishName, hi: englishName, ta: englishName, te: englishName, es: englishName, fr: englishName };
  }

  const clean = normalizeText(englishName);
  const words = clean.split(/\s+/).filter(Boolean);

  // 1. Check exact matches in dictionary
  for (const [key, trans] of Object.entries(COMMODITY_DICTIONARY)) {
    const keyClean = key.replace(/_/g, ' ');
    if (clean === keyClean || clean === keyClean + 's') {
      return {
        en: englishName,
        hi: trans.hi,
        ta: trans.ta,
        te: trans.te,
        es: trans.es,
        fr: trans.fr
      };
    }
  }

  // 2. Multi-word phrase scan (e.g., "sugar cane", "tender coconut", "bitter gourd", "sweet corn")
  const joined = words.join('_');
  if (COMMODITY_DICTIONARY[joined]) {
    const trans = COMMODITY_DICTIONARY[joined];
    return {
      en: englishName,
      hi: trans.hi,
      ta: trans.ta,
      te: trans.te,
      es: trans.es,
      fr: trans.fr
    };
  }

  // Handle common split cases like "sugar cane" -> sugarcane
  const noSpace = words.join('');
  if (COMMODITY_DICTIONARY[noSpace]) {
    const trans = COMMODITY_DICTIONARY[noSpace];
    return {
      en: englishName,
      hi: trans.hi,
      ta: trans.ta,
      te: trans.te,
      es: trans.es,
      fr: trans.fr
    };
  }

  // 3. Scan for any matching commodity keyword inside the phrase (e.g. "Nagpur Fresh Sugarcane 50kg" -> sugarcane)
  let foundCommodity = null;
  let detectedModifier = null;

  for (const word of words) {
    // Check modifiers
    if (MODIFIERS[word]) {
      detectedModifier = MODIFIERS[word];
    }
    // Check singular and plural
    const singular = word.endsWith('s') && word.length > 3 ? word.slice(0, -1) : word;
    if (COMMODITY_DICTIONARY[word]) {
      foundCommodity = COMMODITY_DICTIONARY[word];
      break;
    } else if (COMMODITY_DICTIONARY[singular]) {
      foundCommodity = COMMODITY_DICTIONARY[singular];
      break;
    }
  }

  // Also check 2-word combinations in the phrase
  if (!foundCommodity) {
    for (let i = 0; i < words.length - 1; i++) {
      const pair = `${words[i]}_${words[i+1]}`;
      const pairMerged = `${words[i]}${words[i+1]}`;
      if (COMMODITY_DICTIONARY[pair]) {
        foundCommodity = COMMODITY_DICTIONARY[pair];
        break;
      }
      if (COMMODITY_DICTIONARY[pairMerged]) {
        foundCommodity = COMMODITY_DICTIONARY[pairMerged];
        break;
      }
    }
  }

  if (foundCommodity) {
    if (detectedModifier) {
      return {
        en: englishName,
        hi: `${detectedModifier.hi} ${foundCommodity.hi}`,
        ta: `${detectedModifier.ta} ${foundCommodity.ta}`,
        te: `${detectedModifier.te} ${foundCommodity.te}`,
        es: `${foundCommodity.es} ${detectedModifier.es}`,
        fr: `${foundCommodity.fr} ${detectedModifier.fr}`
      };
    }
    return {
      en: englishName,
      hi: foundCommodity.hi,
      ta: foundCommodity.ta,
      te: foundCommodity.te,
      es: foundCommodity.es,
      fr: foundCommodity.fr
    };
  }

  // Fallback: return the original english name if completely novel/unknown
  return {
    en: englishName,
    hi: englishName,
    ta: englishName,
    te: englishName,
    es: englishName,
    fr: englishName
  };
}

/**
 * Quick direct translator for a single target language
 */
export function getDirectTranslation(englishName, targetLang = 'en') {
  if (!englishName || targetLang === 'en') return englishName;
  const bundle = translateProduceName(englishName);
  return bundle[targetLang] || englishName;
}
