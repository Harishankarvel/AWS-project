import { translateProduceName } from './produceDictionary';

// Dynamic storage for runtime-added products (persisted in memory / localStorage)
let dynamicTranslations = {};

export const registerProductTranslations = (productId, translationsBundle) => {
  dynamicTranslations[productId] = translationsBundle;
};

/**
 * Returns the translated product name for the given language.
 * 1. Checks direct embedded translations on product object
 * 2. Checks hardcoded static catalogue translations
 * 3. Checks dynamic product translations (registered when added by seller)
 * 4. Runs automatic dictionary translation on product.name if not yet bundled
 * 5. Falls back to product.name or original clean name (NEVER displays raw 'custom_...' ID)
 */
export const getProductName = (productOrId, language = 'en') => {
  if (!productOrId) return '';
  
  // Support both passing product object or productId string
  const isObj = typeof productOrId === 'object' && productOrId !== null;
  const id = isObj ? productOrId.id : (typeof productOrId === 'string' ? productOrId : null);
  const rawName = isObj ? productOrId.name : null;
  const embeddedTranslations = isObj ? productOrId.translations : null;

  // 1. Direct embedded translations on product object
  if (embeddedTranslations && embeddedTranslations[language]) {
    return embeddedTranslations[language];
  }

  // 2. Static catalogue translations (by ID)
  if (id && PRODUCT_TRANSLATIONS[id] && PRODUCT_TRANSLATIONS[id][language]) {
    return PRODUCT_TRANSLATIONS[id][language];
  }

  // 3. Dynamic runtime-registered translations (by ID)
  if (id && dynamicTranslations[id] && dynamicTranslations[id][language]) {
    return dynamicTranslations[id][language];
  }

  // 4. On-the-fly dictionary translation if rawName is available
  if (rawName && language !== 'en') {
    const directBundle = translateProduceName(rawName);
    if (directBundle && directBundle[language]) {
      return directBundle[language];
    }
  }

  // 5. English fallbacks: never show raw ID
  if (embeddedTranslations && embeddedTranslations['en']) {
    return embeddedTranslations['en'];
  }
  if (id && PRODUCT_TRANSLATIONS[id] && PRODUCT_TRANSLATIONS[id]['en']) {
    return PRODUCT_TRANSLATIONS[id]['en'];
  }
  if (rawName) {
    return rawName;
  }

  // If only a custom ID string was passed without product object, do not display raw ID
  if (typeof productOrId === 'string') {
    if (productOrId.startsWith('custom_')) {
      // Look up in dynamicTranslations
      if (dynamicTranslations[productOrId] && dynamicTranslations[productOrId][language]) {
        return dynamicTranslations[productOrId][language];
      }
      if (dynamicTranslations[productOrId] && dynamicTranslations[productOrId]['en']) {
        return dynamicTranslations[productOrId]['en'];
      }
      return 'Fresh Farm Produce';
    }
  }

  return rawName || 'Fresh Farm Produce';
};
